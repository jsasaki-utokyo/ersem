#include "fabm_driver.h"

! Shear coagulation and disaggregation of a phytoplankton functional type: a mass transfer between two pools of
! the same type, the single cells (donors: P1) and the aggregates (receivers: P1A), on every constituent
! (carbon, nitrogen, phosphorus, silicate, chlorophyll). TB-FVCOM box-ersem docs/aggregation_sinking.md section 4.3
! (design review PASS, gpt-6.2-sol round 6); jsasaki 2026-11-28.
!
!   phi1     = v_C * C_P1                                         single cells only (stage 1); raw stock, no background
!   gamma_c  = <sqrt(eps)> / sqrt(nu)                              mean shear for coagulation       [s-1]
!   gamma2_b = <eps> / nu                                          mean square shear for break-up   [s-2]
!   k_agg    = k0 + (8/pi) alpha_c gamma_c phi1                    single cells -> aggregates       [s-1]
!   k_dis    = min( k_d gamma2_b / gamma_b^2 , k_dis_max )         aggregates -> single cells       [s-1]
!   dX_donor/dt|agg    = - k_agg X_donor + k_dis X_receiver        for X in {c, n, p, s, chl}
!   dX_receiver/dt|agg = + k_agg X_donor - k_dis X_receiver
!
! The sources are equal and opposite for every constituent, so every conserved quantity is unchanged by the module. The
! module is the only new process; the aggregate pool is an ordinary producer instance (primary_producer with
! isw_agg_pool = 1, sinking rm = w_A) generated by the host configuration. Not used by any existing configuration:
! the module acts only when an instance is declared.
!
! Shear source (host): shear_source = 1 (default) reads the two moments <sqrt(eps)> (m s-3/2) and <eps> (m2 s-3),
! linked by the host under the standard names box_shear_sqrt_dissipation and box_shear_dissipation (TB-FVCOM box driver
! shear_file); shear_source = 2 reads one constant shear rate (s-1) named box_shear_rate (box driver &box_env), used for
! both coagulation (gamma_c) and break-up (gamma2_b = gamma_c^2). c_star > 0 replaces the single-cell carbon of the
! collision term by that fixed value (the concentration-independent control AGL); 0 (default) = the actual carbon.
!
! Rates are given per day (the time unit of the module is the day, as in all ERSEM modules) except nu, gamma_b
! and the shear, which are SI; internal arithmetic is in SI (s-1) and converted to the module time unit at the end.

module ersem_phyto_aggregation

   use fabm_types

   implicit none

   private

   integer, parameter :: max_target = 6
   real(rk), parameter :: pi_agg = 3.14159265358979323846_rk
   real(rk), parameter :: sec_per_day = 86400.0_rk

   type, extends(type_base_model), public :: type_ersem_phyto_aggregation
      type (type_state_variable_id)     :: id_donor(max_target), id_receiver(max_target)
      type (type_dependency_id)         :: id_sqrt_eps, id_eps, id_shear
      type (type_diagnostic_variable_id) :: id_k_agg, id_k_dis, id_gamma_c, id_phi1, id_f_agg
      type (type_diagnostic_variable_id) :: id_flux_coll, id_flux_lin, id_flux_rev
      integer  :: ntarget, shear_source
      real(rk) :: alpha_c, v_C, k0, k_d, gamma_b, k_dis_max, nu, c_star
   contains
      procedure :: initialize => aggregation_initialize
      procedure :: do         => aggregation_do
   end type

contains

   subroutine aggregation_initialize(self, configunit)
      class (type_ersem_phyto_aggregation), intent(inout), target :: self
      integer,                              intent(in)            :: configunit

      integer :: i
      character(len=8) :: idx

      self%dt = sec_per_day   ! rates (sources and diagnostics) in d-1, converted by FABM

      call self%get_parameter(self%ntarget, 'ntarget', '', 'number of constituents transferred (donor1..: c, n, p, s, chl; donor1 = carbon)', &
                              default=5, minimum=1, maximum=max_target)
      call self%get_parameter(self%shear_source, 'shear_source', '', 'turbulence input: 1 = the two dissipation moments of a file, 2 = one constant shear rate', &
                              default=1, minimum=1, maximum=2)
      call self%get_parameter(self%alpha_c, 'alpha_c', '-', 'collision efficiency times the constant correction factor', &
                              default=0.3_rk, minimum=0.0_rk)
      call self%get_parameter(self%v_C, 'v_C', 'm^3/m^3 per mg C/m^3', 'cell volume fraction per unit of single-cell carbon', &
                              default=1.0e-8_rk, minimum=0.0_rk)
      call self%get_parameter(self%k0, 'k0', '1/d', 'linear (stochastic) transfer rate of single cells to aggregates', &
                              default=0.02_rk, minimum=0.0_rk)
      call self%get_parameter(self%k_d, 'k_d', '1/d', 'break-up rate at the reference shear gamma_b', default=0.1_rk, &
                              minimum=0.0_rk)
      call self%get_parameter(self%gamma_b, 'gamma_b', '1/s', 'reference shear of the break-up rate (root mean square)', &
                              default=1.5_rk, minimum=1.0e-6_rk)
      call self%get_parameter(self%k_dis_max, 'k_dis_max', '1/d', 'upper cap of the break-up rate', default=5.0_rk, &
                              minimum=0.0_rk)
      call self%get_parameter(self%nu, 'nu', 'm^2/s', 'kinematic viscosity (fixed; registered 1.4e-6)', default=1.4e-6_rk, &
                              minimum=1.0e-9_rk)
      call self%get_parameter(self%c_star, 'c_star', 'mg C/m^3', 'fixed carbon of the collision term (0 = the actual single-cell carbon)', &
                              default=0.0_rk, minimum=0.0_rk)

      do i = 1, self%ntarget
         write (idx, '(i0)') i
         call self%register_state_dependency(self%id_donor(i), 'donor'//trim(idx), '', 'single-cell constituent '//trim(idx))
         call self%register_state_dependency(self%id_receiver(i), 'receiver'//trim(idx), '', 'aggregate constituent '//trim(idx))
      end do

      if (self%shear_source == 1) then
         call self%register_dependency(self%id_sqrt_eps, type_interior_standard_variable(name='box_shear_sqrt_dissipation', units='m s-3/2'))
         call self%register_dependency(self%id_eps, type_interior_standard_variable(name='box_shear_dissipation', units='m2 s-3'))
      else
         call self%register_dependency(self%id_shear, type_interior_standard_variable(name='box_shear_rate', units='s-1'))
      end if

      call self%register_diagnostic_variable(self%id_k_agg, 'k_agg', '1/d', 'single cells to aggregates, specific rate')
      call self%register_diagnostic_variable(self%id_k_dis, 'k_dis', '1/d', 'aggregates to single cells, specific rate')
      call self%register_diagnostic_variable(self%id_gamma_c, 'gamma_c', '1/s', 'shear of the collision term')
      call self%register_diagnostic_variable(self%id_phi1, 'phi1', 'm^3/m^3', 'single-cell volume fraction of the collision term')
      call self%register_diagnostic_variable(self%id_flux_coll, 'flux_coll', 'mg C/m^3/d', 'carbon transfer to aggregates by collisions')
      call self%register_diagnostic_variable(self%id_flux_lin, 'flux_lin', 'mg C/m^3/d', 'carbon transfer to aggregates by the linear term')
      call self%register_diagnostic_variable(self%id_flux_rev, 'flux_rev', 'mg C/m^3/d', 'carbon transfer back to single cells by break-up')
      call self%register_diagnostic_variable(self%id_f_agg, 'f_agg', '-', 'aggregate share of the carbon')
   end subroutine aggregation_initialize

   subroutine aggregation_do(self, _ARGUMENTS_DO_)
      class (type_ersem_phyto_aggregation), intent(in) :: self
      _DECLARE_ARGUMENTS_DO_

      real(rk) :: sqrt_eps, eps, gamma_c, gamma2_b, c1, c1a, cuse, phi1, q, k_coll, k_lin, k_agg, k_dis, x1, x2, tot
      integer  :: i

      _LOOP_BEGIN_
         if (self%shear_source == 1) then
            _GET_(self%id_sqrt_eps, sqrt_eps)
            _GET_(self%id_eps, eps)
            gamma_c = sqrt_eps/sqrt(self%nu)
            gamma2_b = eps/self%nu
         else
            _GET_(self%id_shear, gamma_c)
            gamma2_b = gamma_c*gamma_c
         end if

         _GET_(self%id_donor(1), c1)
         _GET_(self%id_receiver(1), c1a)
         if (self%c_star > 0.0_rk) then
            cuse = self%c_star
         else
            cuse = max(0.0_rk, c1)
         end if
         phi1 = self%v_C*cuse
         q = (8.0_rk/pi_agg)*self%alpha_c*gamma_c   ! s-1 per unit of phi1
         k_coll = q*phi1                              ! s-1
         k_lin = self%k0/sec_per_day                  ! s-1
         k_agg = k_lin + k_coll
         k_dis = min(self%k_d/sec_per_day*gamma2_b/(self%gamma_b*self%gamma_b), self%k_dis_max/sec_per_day)

         do i = 1, self%ntarget
            _GET_(self%id_donor(i), x1)
            _GET_(self%id_receiver(i), x2)
            _SET_ODE_(self%id_donor(i), (-k_agg*x1 + k_dis*x2)*sec_per_day)
            _SET_ODE_(self%id_receiver(i), (k_agg*x1 - k_dis*x2)*sec_per_day)
         end do

         _SET_DIAGNOSTIC_(self%id_k_agg, k_agg*sec_per_day)
         _SET_DIAGNOSTIC_(self%id_k_dis, k_dis*sec_per_day)
         _SET_DIAGNOSTIC_(self%id_gamma_c, gamma_c)
         _SET_DIAGNOSTIC_(self%id_phi1, phi1)
         _SET_DIAGNOSTIC_(self%id_flux_coll, k_coll*c1*sec_per_day)
         _SET_DIAGNOSTIC_(self%id_flux_lin, k_lin*c1*sec_per_day)
         _SET_DIAGNOSTIC_(self%id_flux_rev, k_dis*c1a*sec_per_day)
         tot = c1 + c1a
         if (tot > 0.0_rk) then
            _SET_DIAGNOSTIC_(self%id_f_agg, c1a/tot)
         else
            _SET_DIAGNOSTIC_(self%id_f_agg, 0.0_rk)
         end if
      _LOOP_END_
   end subroutine aggregation_do

end module ersem_phyto_aggregation
